#!/usr/bin/env python3
"""Generate src/forth/font3x5.fs from assets/font/3x5-ascii.otf.

Each glyph is 15 bits (3 cols x 5 rows, row-major, bit 14 = top-left),
stored as two bytes (high byte first) for ASCII 32..127 (96 glyphs, 192 bytes).
Usage: gen_font_fs.py FONT.otf OUT.fs
"""
import sys
from otf2glyphs import load

glyphs = load(sys.argv[1])
lines = []
for code in range(32, 128):
    rows = glyphs.get(chr(code), ["..."] * 6)
    assert rows[5] == "...", f"{chr(code)!r} uses row 5"
    v = int("".join("1" if c == "#" else "0" for r in rows[:5] for c in r), 2)
    lines.append((code, v))

with open(sys.argv[2], "w") as o:
    o.write("\\ GENERATED by tools/gen_font_fs.py from assets/font/3x5-ascii.otf -- do not edit.\n")
    o.write("\\ 3x5 font: 15 bits per glyph, row-major, bit 14 = top-left. ASCII 32..127.\n\n")
    o.write("create font3x5\n")
    for code, v in lines:
        label = chr(code) if 32 < code < 127 else ""
        o.write(f"  $%02X c, $%02X c,  \\ %d %s\n" % (v >> 8, v & 0xFF, code, label))
    o.write("\n\\ ( char -- bits ) 15-bit glyph bitmap; non-ASCII maps to DEL.\n")
    o.write(": glyph@ ( c -- u ) $7F and 32 - dup 0< if drop 0 then 2* font3x5 + dup c@ 8 lshift swap 1+ c@ or ;\n")
